def legacy_effects(effect: dict) -> list[dict]:
    """Adapt the existing single-effect card format to the effect-list format."""
    mapping = {
        "attack": "attack",
        "shield": "gain_shield",
        "strength": "gain_strength",
        "poison": "apply_poison",
        "heal": "heal",
        "regeneration": "apply_regeneration",
    }
    effect_type = effect.get("type")
    if effect_type not in mapping:
        return []
    translated = {key: value for key, value in effect.items() if key != "type"}
    translated["op"] = mapping[effect_type]
    return [translated]